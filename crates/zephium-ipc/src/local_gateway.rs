//! Secret-free Windows local gateway projection and explicit command vocabulary.
use serde::{Deserialize, Serialize};
use specta::Type;

#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize, Type)]
#[serde(rename_all = "snake_case")]
pub enum GatewayStateV1 {
    Unconfigured,
    Configured,
    /// A catalog was explicitly read, not an inference or entitlement check.
    Checked,
    Unavailable,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize, Type)]
#[serde(rename_all = "snake_case")]
pub enum GatewayFaultV1 {
    Invalid,
    NotConfigured,
    Changed,
    Vault,
    Busy,
    Cancelled,
    Unauthorized,
    Forbidden,
    RateLimited,
    Unavailable,
    Timeout,
    Protocol,
    TooLarge,
    Incomplete,
    UsageUnavailable,
}

#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize, Type)]
#[serde(deny_unknown_fields)]
pub struct GatewayViewV1 {
    pub version: u16,
    pub profile: String,
    pub state: GatewayStateV1,
    pub connection_id: Option<String>,
    pub label: Option<String>,
    /// Canonical loopback URL only, never credentials, query or fragment.
    pub base: Option<String>,
    pub models: u32,
    pub checking: bool,
    pub checked_at_ms: Option<String>,
    pub error: Option<GatewayFaultV1>,
}
impl GatewayViewV1 {
    pub fn unavailable(profile: String) -> Self {
        Self {
            version: 1,
            profile,
            state: GatewayStateV1::Unavailable,
            connection_id: None,
            label: None,
            base: None,
            models: 0,
            checking: false,
            checked_at_ms: None,
            error: Some(GatewayFaultV1::Unavailable),
        }
    }
}

/// Every command is main-chrome and current persistent-profile scoped.
/// Save accepts the gateway's own key only as input; no command returns it.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum GatewayCommand {
    Status,
    Save,
    Check,
    Disconnect,
}
impl GatewayCommand {
    pub const ALL: [Self; 4] = [Self::Status, Self::Save, Self::Check, Self::Disconnect];
    pub const fn native(self) -> &'static str {
        match self {
            Self::Status => "gateway_status",
            Self::Save => "gateway_save",
            Self::Check => "gateway_check",
            Self::Disconnect => "gateway_disconnect",
        }
    }
    pub const fn frontend(self) -> &'static str {
        match self {
            Self::Status => "gatewayStatus",
            Self::Save => "gatewaySave",
            Self::Check => "gatewayCheck",
            Self::Disconnect => "gatewayDisconnect",
        }
    }
    pub fn owns(name: &str) -> bool {
        Self::ALL.iter().any(|command| command.native() == name)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    fn generated() -> String {
        let types = specta::Types::default().register::<GatewayViewV1>();
        let types = specta_typescript::Typescript::default()
            .export(&types, specta_serde::Format)
            .unwrap();
        let mut output = String::from("// Generated by zephium-ipc::local_gateway::tests::export_gateway_bindings. Do not edit.\nimport { invoke } from \"@tauri-apps/api/core\";\n\n");
        output.push_str(&types);
        output.push_str("\nexport const commands = {\n");
        for command in GatewayCommand::ALL {
            let (args, values) = if command == GatewayCommand::Save {
                (
                    "expectedProfile: string, expectedConnectionId: string | null, label: string, base: string, key: string",
                    "expectedProfile, expectedConnectionId, label, base, key",
                )
            } else if command == GatewayCommand::Status {
                ("expectedProfile: string", "expectedProfile")
            } else {
                (
                    "expectedProfile: string, expectedConnectionId: string",
                    "expectedProfile, expectedConnectionId",
                )
            };
            output.push_str(&format!(
                "  {}: ({args}): Promise<GatewayViewV1> => invoke(\"{}\", {{ {values} }}),\n",
                command.frontend(),
                command.native()
            ));
        }
        output.push_str("};\n");
        output
            .lines()
            .map(str::trim_end)
            .collect::<Vec<_>>()
            .join("\n")
            + "\n"
    }
    #[test]
    #[ignore = "Explicit deterministic generation; ordinary tests check drift"]
    fn export_gateway_bindings() {
        std::fs::write(
            "../../frame/src/shared/ipc/gateway-bindings.ts",
            generated(),
        )
        .unwrap();
    }
    #[test]
    fn generated_gateway_bindings_are_current() {
        assert_eq!(
            std::fs::read_to_string("../../frame/src/shared/ipc/gateway-bindings.ts").unwrap(),
            generated()
        );
    }
    #[test]
    fn gateway_projection_cannot_reveal_keys_or_claim_subscription_login() {
        let view = serde_json::to_value(GatewayViewV1::unavailable("fixture".into())).unwrap();
        for field in [
            "key",
            "token",
            "access_token",
            "refresh_token",
            "email",
            "subscription",
        ] {
            assert!(view.get(field).is_none());
        }
        assert!(!GatewayCommand::owns("gateway_login"));
        assert!(!GatewayCommand::owns("gateway_import_token"));
        assert!(!GatewayCommand::owns("gateway_save;exec"));
    }
    #[test]
    fn command_registration_retains_profile_and_chrome_guards() {
        let native = std::fs::read_to_string("../../desktop/src/local_gateway.rs").unwrap();
        let root = std::fs::read_to_string("../../desktop/src/lib.rs").unwrap();
        assert_eq!(
            native.matches("#[tauri::command]").count(),
            GatewayCommand::ALL.len()
        );
        for command in GatewayCommand::ALL {
            assert!(native.contains(&format!("pub(crate) async fn {}(", command.native())));
            let capture = native
                .find("let Some(scope_epoch) = registry.capture_scope(&expected)")
                .unwrap();
            let fetch = native[capture..]
                .find("allowed(&caller, &expected, action).await")
                .unwrap()
                + capture;
            assert!(
                capture < fetch,
                "capture scope before the first actor await"
            );
            assert_eq!(
                native
                    .matches("registry.owns_scope(&expected, scope_epoch)")
                    .count(),
                2
            );
            assert!(
                native.contains("if *foreground != current"),
                "metadata-only projections must not rotate scope"
            );
            assert!(root.contains(&format!("local_gateway::{},", command.native())));
        }
        assert!(native.contains("authorize(caller, CallerPolicy::Main, action.native())"));
        assert!(
            native.contains("profiles.private || profiles.current.as_deref() != Some(expected)")
        );
        assert!(root.contains("local_gateway::profiles_changed(&view)"));
        assert!(root.contains("GatewayCommand::owns(invoke.message.command())"));
        for command in [
            GatewayCommand::Save,
            GatewayCommand::Check,
            GatewayCommand::Disconnect,
        ] {
            let signature = native
                .split(&format!("pub(crate) async fn {}(", command.native()))
                .nth(1)
                .unwrap()
                .split(") -> GatewayViewV1")
                .next()
                .unwrap();
            let expected = if command == GatewayCommand::Save {
                "expected_connection_id: Option<String>"
            } else {
                "expected_connection_id: String"
            };
            assert!(
                signature.contains(expected),
                "mutation must carry its compare-and-swap identity"
            );
        }
        assert!(native.contains(
            ".configure_scoped(service_scope, expected_connection_id, label, base, key)"
        ));
        assert!(native.contains(".check_models_scoped(service_scope, expected_connection_id)"));
        assert!(native.contains(".disconnect_scoped(service_scope, expected_connection_id)"));
        assert!(!native.contains("Command::new"));
        assert!(!native.contains("ShellExecute"));
    }
}
