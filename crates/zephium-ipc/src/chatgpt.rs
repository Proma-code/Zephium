//! Secret-free Windows ChatGPT account projection and closed command vocabulary.
use serde::{Deserialize, Serialize};
use specta::Type;

#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize, Type)]
#[serde(rename_all = "snake_case")]
pub enum ChatGptStateV1 {
    SignedOut,
    Connected,
    Unavailable,
}

/// Native storage evidence, independent of email or usable authorization.
#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize, Type)]
#[serde(rename_all = "snake_case")]
pub enum ChatGptPresenceV1 {
    Missing,
    Stored,
    Unavailable,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize, Type)]
#[serde(rename_all = "snake_case")]
pub enum ChatGptFaultV1 {
    Invalid,
    Offline,
    Cancelled,
    Timeout,
    Protocol,
    Vault,
    Unavailable,
    Busy,
}

#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize, Type)]
#[serde(deny_unknown_fields)]
pub struct ChatGptViewV1 {
    pub version: u16,
    pub profile: String,
    pub state: ChatGptStateV1,
    pub email: Option<String>,
    pub presence: ChatGptPresenceV1,
    pub error: Option<ChatGptFaultV1>,
    pub revocation_unconfirmed: bool,
}

impl ChatGptViewV1 {
    pub fn unavailable(profile: String) -> Self {
        Self {
            version: 1,
            profile,
            state: ChatGptStateV1::Unavailable,
            email: None,
            presence: ChatGptPresenceV1::Unavailable,
            error: Some(ChatGptFaultV1::Unavailable),
            revocation_unconfirmed: false,
        }
    }
}

/// Single source of truth for the independently generated account command module.
/// Every command takes `expected_profile: String` and returns `ChatGptViewV1`.
/// Legacy registration recovery only; new subscriptions connect through Codex.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ChatGptCommand {
    Account,
    SignOut,
}
impl ChatGptCommand {
    pub const ALL: [Self; 2] = [Self::Account, Self::SignOut];
    pub const fn native(self) -> &'static str {
        match self {
            Self::Account => "chatgpt_account",
            Self::SignOut => "chatgpt_sign_out",
        }
    }
    pub const fn frontend(self) -> &'static str {
        match self {
            Self::Account => "chatgptAccount",
            Self::SignOut => "chatgptSignOut",
        }
    }
    pub fn owns(name: &str) -> bool {
        Self::ALL.iter().any(|command| command.native() == name)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    fn generated() -> String {
        let types = specta::Types::default().register::<ChatGptViewV1>();
        let types = specta_typescript::Typescript::default()
            .export(&types, specta_serde::Format)
            .unwrap();
        let mut output = String::from(
            "// Generated by zephium-ipc::chatgpt::tests::export_chatgpt_bindings. Do not edit.\nimport { invoke } from \"@tauri-apps/api/core\";\n\n",
        );
        output.push_str(&types);
        output.push_str("\nexport const commands = {\n");
        for command in ChatGptCommand::ALL {
            let (args, values) = ("expectedProfile: string", "expectedProfile");
            output.push_str(&format!(
                "  {}: ({args}): Promise<ChatGptViewV1> => invoke(\"{}\", {{ {values} }}),\n",
                command.frontend(),
                command.native()
            ));
        }
        output.push_str("};\n");
        output
    }
    #[test]
    #[ignore = "Explicit deterministic code generation; ordinary tests check drift"]
    fn export_chatgpt_bindings() {
        std::fs::write(
            "../../frame/src/shared/ipc/chatgpt-bindings.ts",
            generated(),
        )
        .unwrap();
    }
    #[test]
    fn generated_chatgpt_bindings_are_current() {
        assert_eq!(
            std::fs::read_to_string("../../frame/src/shared/ipc/chatgpt-bindings.ts").unwrap(),
            generated()
        );
    }
    #[test]
    fn account_commands_have_no_generic_execution_or_token_input() {
        assert!(!ChatGptCommand::owns("work_set_provider_key"));
        assert!(!ChatGptCommand::owns("chatgpt_import_token"));
        assert!(!ChatGptCommand::owns("chatgpt_account;exec"));
        let value = serde_json::to_value(ChatGptViewV1::unavailable("profile".into())).unwrap();
        assert!(value.get("access_token").is_none());
        assert!(value.get("auth_url").is_none());
        assert_eq!(value["state"], "unavailable");
    }
    #[test]
    fn generated_commands_match_closed_native_registration_and_profile_gate() {
        let native = std::fs::read_to_string("../../desktop/src/chatgpt.rs").unwrap();
        let root = std::fs::read_to_string("../../desktop/src/lib.rs").unwrap();
        assert_eq!(
            native.matches("#[tauri::command]").count(),
            ChatGptCommand::ALL.len()
        );
        for command in ChatGptCommand::ALL {
            assert!(native.contains(&format!("pub(crate) async fn {}(", command.native())));
            let capture = native
                .find("let Some(scope_epoch) = registry.capture_scope(&expected)")
                .unwrap();
            let fetch = native[capture..]
                .find("allowed(&caller, &expected, action).await")
                .unwrap()
                + capture;
            assert!(
                capture < fetch,
                "capture scope before the first actor await"
            );
            assert_eq!(
                native
                    .matches("registry.owns_scope(&expected, scope_epoch)")
                    .count(),
                3,
                "actor, unbound-vault observation, and service completion each recheck scope"
            );
            assert!(
                native.contains("if *foreground != current"),
                "metadata-only projections must not rotate scope"
            );
            assert!(root.contains(&format!("chatgpt::{},", command.native())));
        }
        assert!(native.contains("authorize(caller, CallerPolicy::Main, action.native())"));
        assert!(
            native.contains("profiles.private || profiles.current.as_deref() != Some(expected)")
        );
        for retired in [
            "chatgpt_sign_in",
            "chatgpt_cancel",
            "chatgpt_refresh_models",
        ] {
            assert!(!ChatGptCommand::owns(retired));
            assert!(!root.contains(&format!("chatgpt::{retired},")));
        }
        assert!(!native.contains("new_host_id"));
        assert!(!native.contains("set_app_setting"));
        assert!(native.contains("app_setting_readback(HOST_KEY)"));
        assert!(root.contains("chatgpt::profiles_changed(&view)"));
        assert!(root.contains("ChatGptCommand::owns(invoke.message.command())"));
        assert!(native.contains("registry.admit_scope(&expected, scope_epoch, &service)"));
        assert!(native.contains("service.scope().ok()"));
        assert!(native.contains("service.load_scoped(service_scope)"));
        assert!(!native.contains("AccountModelClient"));
    }
}
