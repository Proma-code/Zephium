//! Secret-free original Codex connection. Independent from direct SIWC records.
use serde::{Deserialize, Serialize};
use specta::Type;

#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize, Type)]
#[serde(rename_all = "snake_case")]
pub enum CodexStateV1 {
    Unavailable,
    Preparing,
    SignedOut,
    SigningIn,
    Connected,
    RecoveryRequired,
}
#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize, Type)]
#[serde(rename_all = "snake_case")]
pub enum CodexFaultV1 {
    RuntimeMissing,
    RuntimeUnsupported,
    Invalid,
    Busy,
    Cancelled,
    Timeout,
    Protocol,
    Vault,
    ProfileStorage,
    RecoveryRequired,
    ScopeChanged,
    OutcomeUnknown,
    Unavailable,
}
// One canonical persisted selection representation; IPC adds versioned names,
// not another effort policy or an alias from default to explicit none.
pub use zephium_core::page_choice::{
    CodexEffort as CodexEffortV1, CodexEffortChoice as CodexEffortSelectionV1,
};

#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize, Type)]
#[serde(deny_unknown_fields)]
pub struct CodexModelV1 {
    /// Original picker ID; not a renderer-supplied wire model or source authority.
    pub id: String,
    /// Clean original model display name. Connection/source is separate metadata.
    pub name: String,
    pub efforts: Vec<CodexEffortV1>,
    /// Qualified original default, independent of explicit preset membership.
    pub default_effort: Option<CodexEffortV1>,
}
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize, Type)]
#[serde(deny_unknown_fields)]
pub struct CodexSelectionV1 {
    pub model: String,
    pub effort: CodexEffortSelectionV1,
}
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, Type)]
#[serde(deny_unknown_fields)]
pub struct CodexViewV1 {
    pub version: u16,
    pub profile: String,
    pub state: CodexStateV1,
    pub models: Vec<CodexModelV1>,
    pub selection: Option<CodexSelectionV1>,
    /// Persisted backend intent, independent from current runtime/account availability.
    pub page_selected: bool,
    pub login_attempt: Option<String>,
    pub error: Option<CodexFaultV1>,
    /// Current integration does not expose executor/browser tools or Ultra.
    pub text_only: bool,
    /// Original account observation only; never model admission or API billing.
    pub quota: crate::codex_quota::CodexQuotaViewV1,
}
impl CodexViewV1 {
    pub fn unavailable(profile: String) -> Self {
        Self {
            version: 1,
            profile,
            state: CodexStateV1::Unavailable,
            models: Vec::new(),
            selection: None,
            page_selected: false,
            login_attempt: None,
            error: Some(CodexFaultV1::Unavailable),
            text_only: true,
            quota: Default::default(),
        }
    }
}
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum CodexCommand {
    Account,
    CheckConnection,
    Connect,
    CancelLogin,
    Logout,
    RefreshModels,
    RefreshQuota,
    SelectModel,
}
impl CodexCommand {
    pub const ALL: [Self; 8] = [
        Self::Account,
        Self::CheckConnection,
        Self::Connect,
        Self::CancelLogin,
        Self::Logout,
        Self::RefreshModels,
        Self::RefreshQuota,
        Self::SelectModel,
    ];
    pub const fn native(self) -> &'static str {
        match self {
            Self::Account => "codex_account",
            Self::CheckConnection => "codex_check_connection",
            Self::Connect => "codex_connect",
            Self::CancelLogin => "codex_cancel_login",
            Self::Logout => "codex_logout",
            Self::RefreshModels => "codex_refresh_models",
            Self::RefreshQuota => "codex_refresh_quota",
            Self::SelectModel => "codex_select_model",
        }
    }
    pub const fn frontend(self) -> &'static str {
        match self {
            Self::Account => "codexAccount",
            Self::CheckConnection => "codexCheckConnection",
            Self::Connect => "codexConnect",
            Self::CancelLogin => "codexCancelLogin",
            Self::Logout => "codexLogout",
            Self::RefreshModels => "codexRefreshModels",
            Self::RefreshQuota => "codexRefreshQuota",
            Self::SelectModel => "codexSelectModel",
        }
    }
    pub fn owns(name: &str) -> bool {
        Self::ALL.iter().any(|command| command.native() == name)
    }
}
#[cfg(test)]
mod tests {
    use super::*;
    fn generated() -> String {
        let types = specta::Types::default().register::<CodexViewV1>();
        let types = specta_typescript::Typescript::default()
            .export(&types, specta_serde::Format)
            .unwrap();
        let mut out = String::from(
            "// Generated by zephium-ipc::codex::tests::export_codex_bindings. Do not edit.\nimport { invoke } from \"@tauri-apps/api/core\";\n\n",
        );
        out.push_str(&types);
        out.push_str("\nexport type CodexEffortV1 = CodexEffort;\nexport type CodexEffortSelectionV1 = CodexEffortChoice;\n");
        out.push_str("\nexport const commands = {\n");
        for command in CodexCommand::ALL {
            let (args, values) = match command {
                CodexCommand::Connect | CodexCommand::CancelLogin => (
                    "expectedProfile: string, attempt: string",
                    "expectedProfile, attempt",
                ),
                CodexCommand::SelectModel => (
                    "expectedProfile: string, selection: CodexSelectionV1 | null",
                    "expectedProfile, selection",
                ),
                _ => ("expectedProfile: string", "expectedProfile"),
            };
            out.push_str(&format!(
                "  {}: ({args}): Promise<CodexViewV1> => invoke(\"{}\", {{ {values} }}),\n",
                command.frontend(),
                command.native()
            ));
        }
        out.push_str("};\n");
        out
    }
    #[test]
    #[ignore = "Explicit deterministic code generation; ordinary test checks drift"]
    fn export_codex_bindings() {
        std::fs::write("../../frame/src/shared/ipc/codex-bindings.ts", generated()).unwrap();
    }
    #[test]
    fn generated_codex_bindings_are_current() {
        assert_eq!(
            std::fs::read_to_string("../../frame/src/shared/ipc/codex-bindings.ts").unwrap(),
            generated()
        );
    }
    #[test]
    fn default_choice_is_not_explicit_none_or_an_untyped_missing_value() {
        let default = serde_json::to_value(CodexEffortSelectionV1::Default).unwrap();
        let none =
            serde_json::to_value(CodexEffortSelectionV1::Explicit(CodexEffortV1::None)).unwrap();
        assert_eq!(default, serde_json::json!({"kind":"default"}));
        assert_eq!(none, serde_json::json!({"kind":"explicit","effort":"none"}));
        assert_ne!(default, none);
        assert!(serde_json::from_str::<CodexEffortSelectionV1>("null").is_err());
        assert!(serde_json::from_str::<CodexEffortSelectionV1>("\"none\"").is_err());
        assert!(serde_json::from_value::<CodexEffortSelectionV1>(
            serde_json::json!({"kind":"explicit","effort":"ultra"})
        )
        .is_err());
    }
    #[test]
    fn projection_and_commands_never_carry_auth_or_process_authority() {
        let value =
            serde_json::to_value(CodexViewV1::unavailable("synthetic-profile".into())).unwrap();
        for forbidden in ["token", "email", "auth_url", "path", "command", "thread_id"] {
            assert!(value.get(forbidden).is_none());
        }
        for command in [
            "codex_execute",
            "codex_import_token",
            "codex_set_home",
            "codex_rpc",
        ] {
            assert!(!CodexCommand::owns(command));
        }
        assert_eq!(value["text_only"], true);
        // Documentation may explain why Ultra is absent. Its wire value must
        // not be accepted or generated as an effort variant.
        assert!(serde_json::from_str::<CodexEffortV1>("\"ultra\"").is_err());
        assert!(!generated().contains("\"ultra\""));
    }
}
